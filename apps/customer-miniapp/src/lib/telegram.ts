import { App as CapApp } from '@capacitor/app';
import { Browser } from '@capacitor/browser';
import { isAndroidApp } from './platform';

/**
 * Platform adapter. Thin, defensive wrapper around window.Telegram.WebApp for the Mini App; in the Android APK the same calls map to the
 * native back button / browser or are safe no-ops (ready/expand/haptic/header colours have no Android equivalent here).
 * Everything works (without Telegram features) when the SDK is absent.
 */
interface TgWebApp {
  initData: string;
  colorScheme?: string;
  ready(): void;
  expand(): void;
  close(): void;
  setHeaderColor?(color: string): void;
  setBackgroundColor?(color: string): void;
  disableVerticalSwipes?(): void;
  BackButton?: { show(): void; hide(): void; onClick(cb: () => void): void; offClick(cb: () => void): void };
  HapticFeedback?: { impactOccurred(style: string): void; notificationOccurred(type: string): void };
  openTelegramLink?(url: string): void;
  onEvent?(name: string, cb: () => void): void;
  offEvent?(name: string, cb: () => void): void;
  showConfirm?(message: string, cb: (ok: boolean) => void): void;
}
declare global { interface Window { Telegram?: { WebApp?: TgWebApp } } }

const webApp = (): TgWebApp | undefined => (typeof window === 'undefined' ? undefined : window.Telegram?.WebApp);

/**
 * The signed initData string the backend verifies. NEVER initDataUnsafe, and never a user id typed by anyone.
 * In `vite dev` only, a signed string generated by the backend's dev tool may be supplied (VITE_DEV_INIT_DATA or localStorage) so the
 * UI can be tried in a desktop browser; production builds contain no such path.
 */
export function getInitData(): string {
  const fromTelegram = webApp()?.initData;
  if (fromTelegram) return fromTelegram;
  if (import.meta.env.DEV) {
    try {
      const dev = (import.meta.env.VITE_DEV_INIT_DATA as string | undefined) || window.localStorage.getItem('ds.dev.initData');
      if (dev) return dev;
    } catch { /* storage blocked */ }
  }
  return '';
}

export const insideTelegram = (): boolean => Boolean(webApp()?.initData);

/** 'light' or 'dark' as Telegram reports it; undefined outside Telegram (or on a client too old to say). */
export const telegramColorScheme = (): string | undefined => (insideTelegram() ? webApp()?.colorScheme : undefined);

/** Telegram fires themeChanged when the person switches Telegram's theme while the Mini App is open. */
export function onTelegramTheme(cb: () => void): () => void {
  const tg = webApp();
  if (!tg?.onEvent) return () => undefined;
  tg.onEvent('themeChanged', cb);
  return () => tg.offEvent?.('themeChanged', cb);
}

/** The strip above the Mini App and the page behind it, so no light edge shows around a dark page. */
export function setTelegramColors(header: string, background: string): void {
  const tg = webApp();
  try { tg?.setHeaderColor?.(header); tg?.setBackgroundColor?.(background); } catch { /* old clients */ }
}

export function initTelegram(): void {
  if (isAndroidApp) { initAndroidBack(); return; }
  const tg = webApp();
  if (!tg) return;
  try {
    tg.ready();
    tg.expand();
    tg.disableVerticalSwipes?.();      // pull-down must not close the app while the customer scrolls the menu
  } catch { /* old clients */ }
}

/** Telegram fires viewportChanged when the keyboard opens/closes or the sheet is dragged. */
export function onTelegramViewport(cb: () => void): () => void {
  const tg = webApp();
  if (!tg?.onEvent) return () => undefined;
  tg.onEvent('viewportChanged', cb);
  return () => tg.offEvent?.('viewportChanged', cb);
}

// ---- Android back button. Handlers form a stack: the newest (a sheet/modal) closes first, then the screen's parent route; with nothing
// left the system's normal behaviour applies (leave the app).
const backStack: Array<{ id: number; fn: () => void }> = [];
let backSeq = 0;
let backReady = false;
function initAndroidBack(): void {
  if (backReady) return;
  backReady = true;
  void CapApp.addListener('backButton', () => {
    const top = backStack[backStack.length - 1];
    if (top) top.fn(); else void CapApp.exitApp();
  });
}
/** Registers a back handler (modals call this while open). Returns the unregister function. Telegram has its own native back button. */
export function pushBackHandler(fn: () => void): () => void {
  if (!isAndroidApp) return () => undefined;
  const entry = { id: ++backSeq, fn };
  backStack.push(entry);
  return () => { const i = backStack.indexOf(entry); if (i >= 0) backStack.splice(i, 1); };
}

/** External links (Telegram deep link, maps): the in-app browser on Android, a normal tab elsewhere. */
export async function openExternal(url: string): Promise<void> {
  if (!/^https:\/\//i.test(url)) return;
  if (isAndroidApp) { await Browser.open({ url }); return; }
  window.open(url, '_blank', 'noopener');
}

export function setBackButton(visible: boolean, onBack: () => void): () => void {
  if (isAndroidApp) return visible ? pushBackHandler(onBack) : () => undefined;
  const b = webApp()?.BackButton;
  if (!b) return () => undefined;
  if (visible) { b.show(); b.onClick(onBack); } else b.hide();
  return () => { b.offClick(onBack); };
}

export const haptic = {
  tap(): void { try { webApp()?.HapticFeedback?.impactOccurred('light'); } catch { /* ignore */ } },
  success(): void { try { webApp()?.HapticFeedback?.notificationOccurred('success'); } catch { /* ignore */ } },
  error(): void { try { webApp()?.HapticFeedback?.notificationOccurred('error'); } catch { /* ignore */ } },
};

export function confirmDialog(message: string): Promise<boolean> {
  const tg = webApp();
  if (tg?.showConfirm) return new Promise(resolve => tg.showConfirm!(message, ok => resolve(ok)));
  return Promise.resolve(typeof window !== 'undefined' ? window.confirm(message) : false);
}
